import { esc } from "../utils/format.js";
import { columnBadges } from "../components/badges.js";

const LONG_TEXT = /^(text|mediumtext|longtext|tinytext|json)$/i;
const PLACEHOLDERS = {
  date: "YYYY-MM-DD",
  datetime: "YYYY-MM-DD HH:MM:SS",
  timestamp: "YYYY-MM-DD HH:MM:SS",
  time: "HH:MM:SS",
  year: "YYYY",
};

/** Values of an ENUM('a','b') type, or null. */
function enumValues(type) {
  const match = /^enum\((.*)\)$/is.exec(type);
  if (!match) return null;
  return [...match[1].matchAll(/'((?:[^']|'')*)'/g)].map((m) => m[1].replace(/''/g, "'"));
}

// ===================================================================== rows

/**
 * Form for adding (row = null) or editing one row. Each column has a mode:
 *   value    send what's typed
 *   null     send NULL (nullable columns)
 *   default  leave it out so MySQL fills it in (adding only)
 * Returns { body, read(form) }. read() gives { values } when adding, or
 * { changes, original } when editing, with only the columns that changed.
 */
export function rowEditor(structure, row = null) {
  const adding = row === null;
  const fields = structure.columns.map((col, i) => {
    const current = adding ? undefined : row[col.name];
    const label = `<span class="field-name">${esc(col.name)}</span>${columnBadges(col)}<small>${esc(col.type)}</small>`;

    if (!col.editable) {
      const why = col.generated ? "generated by MySQL" : "binary data, can't be edited here";
      return `<div class="field"><label>${label}</label><div class="field-input"><span class="muted">${why}</span></div></div>`;
    }

    const canDefault = adding && (col.autoIncrement || col.default.kind !== "none" || col.nullable);
    const modes = [["value", "Value"]];
    if (col.nullable) modes.push(["null", "NULL"]);
    if (canDefault) modes.push(["default", col.autoIncrement ? "Auto" : "Default"]);

    let mode = "value";
    if (adding && canDefault) mode = "default";
    else if (!adding && current === null) mode = "null";

    const modeSelect = modes.length > 1
      ? `<select name="mode-${i}" class="mode">${modes
          .map(([v, t]) => `<option value="${v}"${v === mode ? " selected" : ""}>${t}</option>`)
          .join("")}</select>`
      : `<input type="hidden" name="mode-${i}" value="value">`;

    const text = current === null || current === undefined ? "" : String(current);
    const disabled = mode === "value" ? "" : " disabled";
    const options = enumValues(col.type);
    let input;
    if (options) {
      const list = options.includes(text) || !text ? options : [text, ...options];
      input = `<select name="value-${i}"${disabled}>${list
        .map((o) => `<option${o === text ? " selected" : ""}>${esc(o)}</option>`)
        .join("")}</select>`;
    } else if (LONG_TEXT.test(col.dataType)) {
      input = `<textarea name="value-${i}" rows="3"${disabled}>${esc(text)}</textarea>`;
    } else {
      const hint = PLACEHOLDERS[col.dataType] ?? (col.numeric ? "number" : "");
      input = `<input name="value-${i}" value="${esc(text)}" placeholder="${hint}" spellcheck="false"${disabled}>`;
    }

    return `<div class="field">
      <label for="value-${i}">${label}</label>
      <div class="field-input">${modeSelect}${input}</div>
    </div>`;
  });

  return {
    body: `<div class="fields">${fields.join("")}</div>`,

    // Enable the value box only when "Value" is chosen.
    mount(form) {
      form.addEventListener("change", (e) => {
        if (!e.target.matches("select.mode")) return;
        const i = e.target.name.slice(5);
        const input = form.elements[`value-${i}`];
        input.disabled = e.target.value !== "value";
        if (!input.disabled) input.focus();
      });
    },

    read(form) {
      const values = {};
      const changes = {};
      const original = {};
      structure.columns.forEach((col, i) => {
        if (!col.editable) return;
        const mode = form.elements[`mode-${i}`].value;
        if (mode === "default") return;
        const next = mode === "null" ? null : form.elements[`value-${i}`].value;
        if (adding) {
          values[col.name] = next;
          return;
        }
        const before = row[col.name];
        const same = next === null ? before === null : before !== null && String(before) === next;
        if (!same) {
          changes[col.name] = next;
          original[col.name] = before;
        }
      });
      return adding ? { values } : { changes, original };
    },
  };
}

// ================================================================== columns

const COMMON_TYPES = [
  "INT", "INT UNSIGNED", "BIGINT", "TINYINT(1)", "DECIMAL(10,2)", "DOUBLE",
  "VARCHAR(255)", "CHAR(10)", "TEXT", "MEDIUMTEXT", "JSON",
  "DATE", "DATETIME", "TIMESTAMP", "TIME", "YEAR", "BOOLEAN", "ENUM('a','b')",
];
const TIMESTAMP_EXPR = /^(current_timestamp|now|localtime|localtimestamp)\s*(\(\s*\d?\s*\))?$/i;

/**
 * Form for adding (column = null) or changing a column.
 * read() returns { column, position } as the API expects.
 */
export function columnEditor(structure, column = null, { largeTable = false } = {}) {
  const adding = column === null;
  const c = column ?? {
    name: "", type: "", nullable: true, default: { kind: "null" },
    autoIncrement: false, onUpdateCurrentTimestamp: false, comment: "",
  };

  // Default dropdown. A default expression other than CURRENT_TIMESTAMP can't be
  // typed here, but an existing one can be kept as it is.
  const keepExpr = c.default.kind === "expression" && !TIMESTAMP_EXPR.test(c.default.value ?? "");
  let current = c.default.kind === "expression" ? (keepExpr ? "keep" : "now") : c.default.kind;
  const defaults = [["none", "No default"], ["null", "NULL"], ["value", "Value"], ["now", "CURRENT_TIMESTAMP"]];
  if (keepExpr) defaults.push(["keep", `Keep: ${c.default.value}`]);

  const others = structure.columns.filter((x) => x.name !== c.name);
  const positions = [[adding ? "end" : "keep", adding ? "At the end" : "Keep current position"], ["first", "First"]]
    .concat(others.map((x) => [`after:${x.name}`, `After ${x.name}`]));

  const warning = adding
    ? ""
    : `<p class="modal-note">Changing the type or size rewrites the column${largeTable ? " and can take a while on this large table" : ""}.
       Values that don't fit the new type make MySQL stop with an error, and nothing is changed.</p>`;

  const body = `
    ${warning}
    <div class="grid-2">
      <label class="stack">Name <input name="name" value="${esc(c.name)}" spellcheck="false" autofocus required></label>
      <label class="stack">Type <input name="type" value="${esc(c.type)}" list="column-types" spellcheck="false" placeholder="e.g. VARCHAR(100)" required></label>
    </div>
    <datalist id="column-types">${COMMON_TYPES.map((t) => `<option value="${esc(t)}">`).join("")}</datalist>
    <div class="grid-2">
      <label class="stack">Default
        <select name="defaultKind">${defaults
          .map(([v, t]) => `<option value="${v}"${v === current ? " selected" : ""}>${esc(t)}</option>`)
          .join("")}</select></label>
      <label class="stack">Default value
        <input name="defaultValue" value="${c.default.kind === "value" ? esc(c.default.value ?? "") : ""}"
          spellcheck="false" ${current === "value" ? "" : "disabled"}></label>
    </div>
    <div class="checks">
      <label><input type="checkbox" name="nullable"${c.nullable ? " checked" : ""}> Allow NULL</label>
      <label><input type="checkbox" name="autoIncrement"${c.autoIncrement ? " checked" : ""}> AUTO_INCREMENT</label>
      <label><input type="checkbox" name="onUpdate"${c.onUpdateCurrentTimestamp ? " checked" : ""}> ON UPDATE CURRENT_TIMESTAMP</label>
    </div>
    <div class="grid-2">
      <label class="stack">Comment <input name="comment" value="${esc(c.comment ?? "")}"></label>
      <label class="stack">Position
        <select name="position">${positions
          .map(([v, t]) => `<option value="${esc(v)}">${esc(t)}</option>`)
          .join("")}</select></label>
    </div>`;

  return {
    body,
    mount(form) {
      form.elements.defaultKind.addEventListener("change", () => {
        const input = form.elements.defaultValue;
        input.disabled = form.elements.defaultKind.value !== "value";
        if (!input.disabled) input.focus();
      });
    },
    read(form) {
      const f = form.elements;
      const kind = f.defaultKind.value;
      const dflt =
        kind === "now" ? { kind: "expression", value: "CURRENT_TIMESTAMP" }
        : kind === "keep" ? { kind: "expression", value: c.default.value }
        : kind === "value" ? { kind: "value", value: f.defaultValue.value }
        : { kind };

      const pos = f.position.value;
      const position = pos.startsWith("after:") ? { type: "after", column: pos.slice(6) } : { type: pos };

      return {
        column: {
          name: f.name.value,
          type: f.type.value,
          nullable: f.nullable.checked,
          default: dflt,
          autoIncrement: f.autoIncrement.checked,
          onUpdateCurrentTimestamp: f.onUpdate.checked,
          comment: f.comment.value,
        },
        position,
      };
    },
  };
}
